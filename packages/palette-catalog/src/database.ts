import { Pool, type PoolConfig } from "pg";

import { getDatabaseUrl } from "./config";
import { createPublicPaletteId } from "./metadata";

const SCHEMA_VERSION = 3;

export type PaletteDatabase = Pool;
export type PaletteDatabaseConnection = Pick<PaletteDatabase, "query">;

const INITIAL_SCHEMA = `
  CREATE TABLE palettes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relative_path TEXT NOT NULL UNIQUE,
    filename TEXT NOT NULL,
    display_name TEXT NOT NULL,
    mime_type TEXT NOT NULL,
    width INTEGER NOT NULL CHECK (width > 0),
    height INTEGER NOT NULL CHECK (height > 0),
    file_size BIGINT NOT NULL CHECK (file_size >= 0),
    mtime_ms DOUBLE PRECISION NOT NULL,
    sha256 TEXT NOT NULL,
    color_count INTEGER NOT NULL CHECK (color_count > 0),
    unique_color_count INTEGER NOT NULL CHECK (unique_color_count > 0),
    average_lightness DOUBLE PRECISION NOT NULL,
    min_lightness DOUBLE PRECISION NOT NULL,
    max_lightness DOUBLE PRECISION NOT NULL,
    average_chroma DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    scanned_at TIMESTAMPTZ NOT NULL,
    is_favorite BOOLEAN NOT NULL DEFAULT FALSE
  );

  CREATE TABLE palette_colors (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    palette_id INTEGER NOT NULL REFERENCES palettes(id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position >= 0),
    hex TEXT NOT NULL,
    red INTEGER NOT NULL CHECK (red BETWEEN 0 AND 255),
    green INTEGER NOT NULL CHECK (green BETWEEN 0 AND 255),
    blue INTEGER NOT NULL CHECK (blue BETWEEN 0 AND 255),
    ok_l DOUBLE PRECISION NOT NULL,
    ok_a DOUBLE PRECISION NOT NULL,
    ok_b DOUBLE PRECISION NOT NULL,
    chroma DOUBLE PRECISION NOT NULL,
    hue DOUBLE PRECISION,
    relative_luminance DOUBLE PRECISION NOT NULL,
    UNIQUE (palette_id, position)
  );

  CREATE TABLE scan_state (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    last_scanned_at TIMESTAMPTZ NOT NULL,
    discovered_count INTEGER NOT NULL CHECK (discovered_count >= 0),
    failure_count INTEGER NOT NULL CHECK (failure_count >= 0)
  );

  CREATE INDEX palettes_display_name_idx ON palettes(LOWER(display_name));
  CREATE INDEX palettes_color_count_idx ON palettes(color_count);
  CREATE INDEX palettes_mtime_idx ON palettes(mtime_ms);
  CREATE INDEX palettes_favorite_idx ON palettes(is_favorite);
  CREATE INDEX palette_colors_palette_idx ON palette_colors(palette_id);
`;

async function migrate(database: PaletteDatabase) {
  const client = await database.connect();

  try {
    await client.query("BEGIN");
    await client.query(`
      SELECT pg_advisory_xact_lock(
        hashtext(current_database()),
        hashtext(COALESCE(current_schema(), '') || ':palette-town-migrations')
      )
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS schema_migrations (
        version INTEGER PRIMARY KEY,
        applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);

    const result = await client.query<{ version: number }>(`
      SELECT COALESCE(MAX(version), 0)::INTEGER AS version
      FROM schema_migrations
    `);
    const currentVersion = result.rows[0].version;

    if (currentVersion > SCHEMA_VERSION) {
      throw new Error(
        `Database schema ${currentVersion} is newer than supported schema ${SCHEMA_VERSION}.`,
      );
    }

    if (currentVersion < 1) {
      await client.query(INITIAL_SCHEMA);
      await client.query(
        "INSERT INTO schema_migrations (version) VALUES ($1)",
        [1],
      );
    }

    if (currentVersion < 2) {
      await client.query(`
        ALTER TABLE palettes
          ADD COLUMN public_id TEXT,
          ADD COLUMN tags TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
          ADD COLUMN author_name TEXT,
          ADD COLUMN author_url TEXT,
          ADD COLUMN attribution_text TEXT,
          ADD COLUMN attribution_url TEXT,
          ADD COLUMN attribution_license TEXT,
          ADD COLUMN popularity INTEGER NOT NULL DEFAULT 0
            CHECK (popularity BETWEEN 0 AND 2147483647),
          ADD COLUMN format_version INTEGER NOT NULL DEFAULT 1
            CHECK (format_version BETWEEN 1 AND 2);

        ALTER TABLE palette_colors
          ADD COLUMN alpha INTEGER NOT NULL DEFAULT 255
            CHECK (alpha BETWEEN 0 AND 255);
      `);

      const palettes = await client.query<{
        id: number;
        relative_path: string;
      }>("SELECT id, relative_path FROM palettes");
      for (const palette of palettes.rows) {
        await client.query(
          "UPDATE palettes SET public_id = $1 WHERE id = $2",
          [createPublicPaletteId(palette.relative_path), palette.id],
        );
      }

      await client.query(`
        ALTER TABLE palettes ALTER COLUMN public_id SET NOT NULL;
        CREATE UNIQUE INDEX palettes_public_id_idx ON palettes(public_id);
        CREATE INDEX palettes_tags_idx ON palettes USING GIN(tags);
        CREATE INDEX palettes_popularity_idx ON palettes(popularity DESC);
        CREATE INDEX palette_colors_hue_idx ON palette_colors(hue);
      `);
      await client.query(
        "INSERT INTO schema_migrations (version) VALUES ($1)",
        [2],
      );
    }

    if (currentVersion < 3) {
      await client.query(`
        ALTER TABLE palettes
          ADD COLUMN IF NOT EXISTS format_version INTEGER NOT NULL DEFAULT 1
            CHECK (format_version BETWEEN 1 AND 2);

        UPDATE palettes
        SET format_version = 2
        WHERE color_count BETWEEN 1 AND 64
          AND color_count = unique_color_count;

        DROP INDEX IF EXISTS palettes_public_id_idx;

        DO $$
        BEGIN
          IF NOT EXISTS (
            SELECT 1
            FROM pg_constraint
            WHERE conrelid = 'palettes'::regclass
              AND conname = 'palettes_public_id_key'
          ) THEN
            ALTER TABLE palettes
              ADD CONSTRAINT palettes_public_id_key
              UNIQUE (public_id)
              DEFERRABLE INITIALLY DEFERRED;
          END IF;
        END
        $$;
      `);
      await client.query(
        "INSERT INTO schema_migrations (version) VALUES ($1)",
        [3],
      );
    }

    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

export async function openDatabase(
  config: string | PoolConfig = getDatabaseUrl(),
) {
  const database = new Pool(
    typeof config === "string" ? { connectionString: config } : config,
  );
  database.on("error", (error) => {
    console.error("Unexpected PostgreSQL pool error", error);
  });

  try {
    await migrate(database);
    return database;
  } catch (error) {
    await database.end();
    throw error;
  }
}

export async function withDatabaseSnapshot<T>(
  database: PaletteDatabase,
  read: (connection: PaletteDatabaseConnection) => Promise<T>,
) {
  const client = await database.connect();
  let transactionStarted = false;

  try {
    await client.query(
      "BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY",
    );
    transactionStarted = true;
    const result = await read(client);
    await client.query("COMMIT");
    transactionStarted = false;
    return result;
  } catch (error) {
    if (transactionStarted) await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

const databaseGlobal = globalThis as typeof globalThis & {
  paletteTownDatabase?: {
    url: string;
    database: Promise<PaletteDatabase>;
  };
};

export function getDatabase() {
  const url = getDatabaseUrl();
  const current = databaseGlobal.paletteTownDatabase;

  if (current?.url === url) return current.database;

  if (current) {
    void current.database.then((database) => database.end()).catch(() => {});
  }

  const entry = { url, database: openDatabase(url) };
  databaseGlobal.paletteTownDatabase = entry;
  void entry.database.catch(() => {
    if (databaseGlobal.paletteTownDatabase === entry) {
      delete databaseGlobal.paletteTownDatabase;
    }
  });

  return entry.database;
}
